import json
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':900})
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://localhost:3000')
 page.get_by_role('heading',name='Visão geral',exact=True).wait_for()
 assert page.get_by_text('0h 00min',exact=True).is_visible()
 page.get_by_role('button',name='Roadmap',exact=True).click()
 page.get_by_label('Nome do assunto').fill('Interpretação textual')
 page.get_by_role('button',name='Adicionar tópico',exact=True).click()
 page.get_by_label('Concluir Interpretação textual').check()
 page.get_by_label('Compartilhar Interpretação textual com outro concurso').select_option('CBMPE — Soldado')
 page.get_by_label('Concurso',exact=True).select_option('CBMPE — Soldado')
 assert page.get_by_label('Concluir Interpretação textual').is_checked()
 page.reload()
 page.get_by_role('button',name='Roadmap',exact=True).click()
 assert page.get_by_label('Concluir Interpretação textual').is_checked()
 page.get_by_role('button',name='Planejamento',exact=True).click()
 page.get_by_label('Título da tarefa').fill('Revisar conteúdo')
 page.get_by_role('button',name='Adicionar',exact=True).click()
 page.get_by_label('Concluir Revisar conteúdo').check()
 page.reload()
 page.get_by_role('button',name='Planejamento',exact=True).click()
 assert page.get_by_label('Concluir Revisar conteúdo').is_checked()
 page.get_by_role('button',name='Cronômetro',exact=True).click()
 page.get_by_role('button',name='Iniciar',exact=True).click()
 page.wait_for_timeout(1200)
 page.reload()
 page.get_by_role('button',name='Cronômetro',exact=True).click()
 assert page.get_by_role('button',name='Pausar',exact=True).is_visible()
 page.get_by_role('button',name='Pausar',exact=True).click()
 # Advance the persisted clock to test a recorded session without waiting a minute.
 page.evaluate("""() => {const d=JSON.parse(localStorage.getItem('aprovape-v1'));d.state.timer.elapsed=65000;localStorage.setItem('aprovape-v1',JSON.stringify(d))}""")
 page.reload()
 page.get_by_role('button',name='Cronômetro',exact=True).click()
 page.get_by_role('button',name='Registrar sessão',exact=True).click()
 assert page.get_by_text('1 min',exact=True).is_visible()
 page.get_by_role('button',name='Backup',exact=True).click()
 with page.expect_download() as d:page.get_by_role('button',name='Baixar backup JSON').click()
 downloaded=json.load(open(d.value.path()))
 assert downloaded['data']['sessions'][0]['minutes']==1
 page.on('dialog',lambda d:d.accept())
 page.locator('input[type=file]').set_input_files({'name':'backup.json','mimeType':'application/json','buffer':json.dumps(downloaded).encode()})
 page.get_by_role('button',name='Visão geral',exact=True).click()
 assert page.get_by_text('0h 01min',exact=True).is_visible()
 page.wait_for_timeout(1200)
 page.screenshot(path='/tmp/aprovape-desktop.png',full_page=True)
 for width in [390,360,320]:
  page.set_viewport_size({'width':width,'height':844})
  assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
  page.get_by_role('button',name='Abrir menu').click()
  page.get_by_role('button',name='Roadmap',exact=True).click()
  assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
  page.get_by_role('button',name='Abrir menu').click()
  page.get_by_role('button',name='Cronômetro',exact=True).click()
  assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
 page.screenshot(path='/tmp/aprovape-mobile.png',full_page=True)
 # Invalid local data must not hang loading or overwrite the original payload.
 page.evaluate("localStorage.setItem('aprovape-v1','{invalid')")
 page.reload()
 page.locator('.error-banner').wait_for()
 assert page.evaluate("localStorage.getItem('aprovape-v1')")=='{invalid'
 assert not errors,errors
 print('PASS: initial empty state, shared roadmap, checklist, reload persistence, timer, sessions, backup round trip, real metrics, 320/360/390px layouts, corrupt storage recovery; no browser errors.')
 browser.close()
